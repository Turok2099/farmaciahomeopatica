import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { config } from 'dotenv';
import { neon } from '@neondatabase/serverless';
config({ path: '.env.local', quiet: true });
const { CLOUDINARY_CLOUD_NAME: cloud, CLOUDINARY_API_KEY: key, CLOUDINARY_API_SECRET: secret } = process.env;
const file = 'C:/Users/jorge/Documents/Codex/2026-10-21/las-x20/outputs/imagenes-catalogo/magnesium-1l-frente-v01.png';
const timestamp = Math.round(Date.now() / 1000);
const params = { invalidate: 'true', overwrite: 'true', public_id: 'productos/magnesium-1l', timestamp };
const sig = createHash('sha1').update(Object.keys(params).sort().map(k => `${k}=${params[k]}`).join('&') + secret).digest('hex');
const body = new FormData();
body.set('file', new Blob([readFileSync(file)], { type: 'image/png' }), 'magnesium-1l.png');
for (const [k, v] of Object.entries(params)) body.set(k, String(v));
body.set('api_key', key); body.set('signature', sig);
const r = await fetch(`https://api.cloudinary.com/v1_1/${cloud}/image/upload`, { method: 'POST', body });
const j = await r.json(); if (!r.ok) throw new Error(j.error?.message);
const sql = neon(process.env.DATABASE_URL);
console.log(await sql`update products set image_id=${j.public_id}, updated_at=now() where slug='magnesium-litro' returning name, image_id`);
const t = await fetch(`https://res.cloudinary.com/${cloud}/image/upload/f_auto,q_auto,w_600/${j.public_id}`);
console.log('imagen carga:', t.status);
